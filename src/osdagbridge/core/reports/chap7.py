from osdagbridge.core.reports import styles as S
from osdagbridge.core.reports import report_charts as RC
import os


def _qty(input_dict, key):
    """Numeric quantity from the BOM dict ('N.A.' / missing -> None)."""
    return RC.parse_number(input_dict.get(key))


def material_quantity_chart_tex(input_dict, images_dir):
    """Figure 7.1: steel tonnage by component and deck concrete vs reinforcement."""
    if not images_dir:
        return ""
    bracing = [_qty(input_dict, f"bracing_{p}_wt_total") for p in ("top", "bot", "diag")]
    bracing_total = sum(b for b in bracing if b is not None) if any(b is not None for b in bracing) else None
    steel = [("Girders", _qty(input_dict, "steel_girders_wt_total")),
             ("Cross Bracing", bracing_total)]
    try:
        png = RC.material_chart(
            steel,
            _qty(input_dict, "concrete_deck_vol_total"),
            _qty(input_dict, "rebar_deck_wt_total"),
            os.path.join(images_dir, "material_quantities.png"),
            note="End diaphragms are not itemised separately in Table 7.1.")
    except Exception:
        png = None   # a chart failure must never break the report
    return RC.figure_tex(
        png,
        r"Material quantity summary: (a) structural steel tonnage by component; "
        r"(b) deck concrete volume (m$^3$) vs reinforcement steel weight (MT), from Table 7.1.",
        "fig:material-quantities")


